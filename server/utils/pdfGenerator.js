const PDFDocument = require('pdfkit');

/**
 * Generate official CyberShield Complaint PDF Report
 * @param {Object} complaint - The complaint object populated with citizenId and assignedTo
 * @param {Stream} res - Express response stream
 */
function generateComplaintPDF(complaint, res) {
  const doc = new PDFDocument({ margin: 40, size: 'A4' });

  // Stream PDF directly to client response
  doc.pipe(res);

  // Header Background bar
  doc.rect(40, 40, 515, 60).fill('#0f172a');

  // Title
  doc.fillColor('#38bdf8').fontSize(22).font('Helvetica-Bold')
    .text('CYBERSHIELD', 60, 52, { continued: true })
    .fillColor('#ffffff').fontSize(14).font('Helvetica')
    .text(' | National Incident Report');

  doc.fillColor('#94a3b8').fontSize(10)
    .text('Automated Cybercrime Redressal & Investigation Platform', 60, 78);

  // Tracking ID Badge
  doc.rect(40, 115, 515, 45).fill('#1e293b');
  doc.fillColor('#e2e8f0').fontSize(11).font('Helvetica')
    .text('TRACKING ID / CASE REFERENCE:', 55, 128);
  doc.fillColor('#38bdf8').fontSize(16).font('Helvetica-Bold')
    .text(complaint.trackingId, 280, 124);

  // Section 1: Complaint Details
  let y = 175;
  doc.fillColor('#0f172a').fontSize(13).font('Helvetica-Bold')
    .text('INCIDENT OVERVIEW', 40, y);
  doc.rect(40, y + 18, 515, 2).fill('#38bdf8');

  y += 30;
  const col1 = 45;
  const col2 = 300;

  doc.fillColor('#475569').fontSize(10).font('Helvetica-Bold').text('Category:', col1, y);
  doc.fillColor('#0f172a').font('Helvetica').text(complaint.category || 'N/A', col1 + 80, y);

  doc.fillColor('#475569').font('Helvetica-Bold').text('Current Status:', col2, y);
  doc.fillColor('#0284c7').font('Helvetica-Bold').text(complaint.status || 'Submitted', col2 + 85, y);

  y += 20;
  doc.fillColor('#475569').font('Helvetica-Bold').text('Incident Date:', col1, y);
  doc.fillColor('#0f172a').font('Helvetica').text(
    complaint.incidentDate ? new Date(complaint.incidentDate).toLocaleDateString() : 'N/A',
    col1 + 80, y
  );

  doc.fillColor('#475569').font('Helvetica-Bold').text('Priority Level:', col2, y);
  doc.fillColor(complaint.priority === 'Critical' ? '#dc2626' : '#ea580c').font('Helvetica-Bold')
    .text(complaint.priority || 'Medium', col2 + 85, y);

  y += 20;
  doc.fillColor('#475569').font('Helvetica-Bold').text('Reported On:', col1, y);
  doc.fillColor('#0f172a').font('Helvetica').text(
    complaint.createdAt ? new Date(complaint.createdAt).toLocaleString() : new Date().toLocaleString(),
    col1 + 80, y
  );

  // Section 2: Complainant Information
  y += 35;
  doc.fillColor('#0f172a').fontSize(13).font('Helvetica-Bold')
    .text('COMPLAINANT DETAILS', 40, y);
  doc.rect(40, y + 18, 515, 2).fill('#38bdf8');

  y += 30;
  const citizen = complaint.citizenId || {};
  doc.fillColor('#475569').fontSize(10).font('Helvetica-Bold').text('Full Name:', col1, y);
  doc.fillColor('#0f172a').font('Helvetica').text(citizen.name || 'Anonymous / Registered User', col1 + 80, y);

  doc.fillColor('#475569').font('Helvetica-Bold').text('Contact Phone:', col2, y);
  doc.fillColor('#0f172a').font('Helvetica').text(citizen.phone || 'N/A', col2 + 85, y);

  y += 20;
  doc.fillColor('#475569').font('Helvetica-Bold').text('Registered Email:', col1, y);
  doc.fillColor('#0f172a').font('Helvetica').text(citizen.email || 'N/A', col1 + 95, y);

  // Section 3: Description & Narrative
  y += 35;
  doc.fillColor('#0f172a').fontSize(13).font('Helvetica-Bold')
    .text('INCIDENT DESCRIPTION', 40, y);
  doc.rect(40, y + 18, 515, 2).fill('#38bdf8');

  y += 28;
  doc.fillColor('#0f172a').fontSize(11).font('Helvetica-Bold').text(complaint.title || '', col1, y);

  y += 18;
  doc.fillColor('#334155').fontSize(10).font('Helvetica')
    .text(complaint.description || 'No description provided.', col1, y, {
      width: 505,
      align: 'justify',
      lineGap: 3
    });

  // Footer & Disclaimer
  doc.fontSize(8).fillColor('#64748b')
    .text(
      'This document is computer-generated by the CyberShield Threat Intelligence & Reporting System. ' +
      'It serves as an official complaint acknowledgement receipt for legal and administrative procedures.',
      40, 750, { width: 515, align: 'center' }
    );

  doc.end();
}

module.exports = { generateComplaintPDF };
